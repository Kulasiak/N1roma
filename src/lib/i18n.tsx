const DICTIONARIES: Record<Locale, Record<TranslationKey, string>> = { it, en, es }

export type Translate = (key: TranslationKey, params?: Record<string, string | number>) => string

interface I18nValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: Translate
}

const I18nContext = createContext<I18nValue | null>(null)
const STORAGE_KEY = 'onda.locale'

function initialLocale(): Locale {
  if (typeof window === 'undefined') return 'it'
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored === 'it' || stored === 'en' || stored === 'es') return stored
  } catch {
    // Storage non leggibile: si ricade sulla lingua del browser.
  }
  const browser = window.navigator.language.slice(0, 2)
  return browser === 'en' || browser === 'es' ? browser : 'it'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)

  // Allinea i formattatori di date e valuta prima del primo render.
  setFormatLocale(LOCALES.find((l) => l.id === locale)!.intl)

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next)
    setFormatLocale(LOCALES.find((l) => l.id === next)!.intl)
    document.documentElement.lang = next
    try {
      window.localStorage.setItem(STORAGE_KEY, next)
    } catch {
      // Preferenza non persistibile: vale per la sessione.
    }
  }, [])

  const t = useCallback<Translate>((key, params) => {
    let text: string = DICTIONARIES[locale][key] ?? it[key] ?? key
    if (params) for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
    return text
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n deve essere usato dentro <I18nProvider>')
  return ctx
}
